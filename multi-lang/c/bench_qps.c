/*
 * QZDB reference-compliant benchmark for C  (docs/BENCH_CONTRACT.md v1.0)
 *
 * Implements:
 *   - splitmix64 reference RNG (byte-identical to the 7 other language benches)
 *   - four distributions: random / hot / sequential / real_world
 *   - dual-stack tri-mode: v4 / v6 / mixed(50-40-10)
 *   - QPS / avg / P50 / P95 / P99, cold vs hot
 *   - thread scaling 1/2/4/8/16 on ONE shared reader  + 16x100k concurrency gate
 *   - canonical JSON -> multi-lang/bench_reports/c_<edition>.json
 *
 * Parity guard: the FNV-1a 64 of the first 1024 queries of every stream is
 * compared against the value baked into bench_vectors.h (generated by
 * tools/bench_gen.py from the same manifest the other languages read). A match
 * proves the whole 2M-query stream is byte-identical to Python's, by
 * construction.
 *
 * C has a fill-only, immutable, lock-free decode cache (see qzdb_reader.h), so
 * unlike the managed runtimes its shared-reader thread scaling should stay
 * near-linear. That contrast is exactly what this contract exists to surface.
 *
 * Env overrides:  BENCH_OPS=200000   BENCH_EDITIONS=std_china
 */

