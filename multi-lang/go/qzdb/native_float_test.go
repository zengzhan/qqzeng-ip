// TestFormatFloat6Boundaries 原生浮点格式化统一契约边界（FORMAT §10.5 / P0-2）。
// 与 python/test_native_float.py、nodejs/native_float_test.js 用例逐字同源；
// C/Rust/PHP 侧同名断言见各语言测试。
func TestFormatFloat6Boundaries(t *testing.T) {
	cases := []struct {
		in   float64
		want string
		note string
	}{
		{116.0, "116", "整值无小数点"},
		{-3.0, "-3", "负整值"},
		{0, "0", "零"},
		{math.Copysign(0, -1), "0", "负零归一"},
		{116.4, "116.400000", "非整数固定 6 位"},
		{-3.5, "-3.500000", "负非整数"},
		{math.NaN(), "", "NaN"},
		{math.Inf(1), "", "+Inf"},
		{math.Inf(-1), "", "-Inf"},
		{1e16, "10000000000000000", "2^53 整值（int64 路径）"},
		{9.2e18, "9200000000000000000", "int64 上界内大整值"},
		{9223372036854774784.0, "9223372036854774784", "< 2^63 最大可表示偶数整值"},
		{9223372036854775808.0, "9223372036854775808", "恰为 2^63 走定点分支"},
		{-9223372036854775808.0, "-9223372036854775808", "恰为 -2^63"},
		{1e20, "100000000000000000000", "> 2^63 定点整数位"},
		{1e300, exactExpansionOf1e300, "1e300 定点展开精确值（非精确可表示）"},
		{-1e300, "-" + exactExpansionOf1e300, "-1e300"},
	}
	for _, c := range cases {
		if got := formatFloat6(c.in); got != c.want {
			t.Errorf("formatFloat6(%v) [%s] = %q, want %q", c.in, c.note, got, c.want)
		}
	}
}
